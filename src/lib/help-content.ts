/** Простой поиск по инструкциям: все слова запроса должны встретиться в теме. */
export function searchHelp(query: string, topics = HELP_TOPICS): HelpTopic[] {
  const words = query.toLowerCase().replace(/ё/g, "е").split(/\s+/).filter((w) => w.length >= 2);
  if (!words.length) return topics;
  return topics.filter((t) => {
    const hay = [t.title, t.summary, t.who, ...t.steps, ...t.mistakes, t.result, ...(t.faq ?? []).flatMap((f) => [f.q, f.a])].join(" ").toLowerCase().replace(/ё/g, "е");
    return words.every((w) => hay.includes(w));
  });
}

